#!/usr/bin/env bash
# ==============================================================================
# OpsAcademy Production Deployment Script for AWS EC2 (Ubuntu 22.04 / 24.04 LTS)
# ==============================================================================
set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}==============================================================================${NC}"
echo -e "${BLUE}        OpsAcademy Production EC2 Automated Deployment & Provisioner        ${NC}"
echo -e "${BLUE}==============================================================================${NC}"

# 1. Root / Sudo Check
if [ "$EUID" -ne 0 ]; then
  echo -e "${RED}[ERROR] Please run this script with sudo: sudo ./scripts/deploy-ec2.sh${NC}"
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${ROOT_DIR}"

# 2. Install Docker & Docker Compose if missing
if ! command -v docker &> /dev/null; then
  echo -e "${YELLOW}[1/6] Installing Docker Engine and Compose plugin...${NC}"
  apt-get update -y
  apt-get install -y ca-certificates curl gnupg lsb-release
  mkdir -p /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg --yes
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu $(lsb_release -cs) stable" | tee /etc/apt/sources.list.d/docker.list > /dev/null
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
else
  echo -e "${GREEN}[1/6] Docker is already installed: $(docker --version)${NC}"
fi

# 3. Apply Kernel Tuning for High-Concurrency WebSockets & Sandboxes
echo -e "${YELLOW}[2/6] Applying Linux kernel optimizations for WebSocket concurrency...${NC}"
SYSCTL_FILE="/etc/sysctl.d/99-opsacademy.conf"
cat <<EOF > "${SYSCTL_FILE}"
# OpsAcademy Concurrency & High I/O Settings
fs.file-max = 2097152
fs.inotify.max_user_watches = 524288
fs.inotify.max_user_instances = 8192
net.core.somaxconn = 65535
net.ipv4.ip_local_port_range = 1024 65535
vm.max_map_count = 262144
vm.swappiness = 10
EOF
sysctl --system > /dev/null 2>&1 || true

# 4. Generate .env.production with cryptographically secure secrets if not present
ENV_FILE="${ROOT_DIR}/.env.production"
if [ ! -f "${ENV_FILE}" ]; then
  echo -e "${YELLOW}[3/6] Generating new .env.production with secure cryptographic secrets...${NC}"
  CERT_SECRET=$(openssl rand -hex 32)
  AI_HUB_TOKEN=$(openssl rand -hex 24)

  cat <<EOF > "${ENV_FILE}"
# Auto-generated by deploy-ec2.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
DOMAIN=localhost
ACME_EMAIL=admin@localhost

CERT_SECRET=${CERT_SECRET}
AI_HUB_TOKEN=${AI_HUB_TOKEN}
# Verified email of the first platform admin (operator page /admin)
PLATFORM_ADMIN_EMAILS=
METRICS_TOKEN=

# Data lives in Supabase Postgres. DATABASE_URL is the transaction-pooler string (required);
# MIGRATION_DATABASE_URL is the direct connection used to apply migrations (optional).
DATABASE_URL=
MIGRATION_DATABASE_URL=
DATABASE_POOL_SIZE=10
SUPABASE_URL=
SUPABASE_PUBLISHABLE_KEY=
SUPABASE_SECRET_KEY=

APP_URL=http://localhost
CLIENT_URL=http://localhost
CORS_ORIGINS=http://localhost

ANTHROPIC_API_KEY=
GROQ_API_KEY=
LLM_PROVIDER=auto
AI_HUB_TIMEOUT_MS=10000
WITH_SEMANTIC=true

SANDBOX_MAX_TOTAL=45
SANDBOX_POOL_SIZE=5
SANDBOX_MEMORY_MB=256
SANDBOX_CPUS=0.5
CAMPUS_IPS=
CAMPUS_RATE_MULTIPLIER=15
EOF
  chmod 600 "${ENV_FILE}"
  echo -e "${GREEN}Created ${ENV_FILE} (mode 600) with auto-generated secrets.${NC}"
  echo -e "${YELLOW}[NOTICE] Edit ${ENV_FILE} to set your custom DOMAIN, ACME_EMAIL, and the SUPABASE_ keys.${NC}"
else
  echo -e "${GREEN}[3/6] Existing .env.production found.${NC}"
fi

# 5. Setup Systemd Service for Auto-Restart on EC2 Reboot
echo -e "${YELLOW}[4/6] Configuring systemd service for zero-touch boot recovery...${NC}"
SERVICE_FILE="/etc/systemd/system/opsacademy.service"
cat <<EOF > "${SERVICE_FILE}"
[Unit]
Description=OpsAcademy Container Platform
Requires=docker.service
After=docker.service network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=${ROOT_DIR}
ExecStart=/usr/bin/docker compose -f docker-compose.prod.yml --env-file .env.production up -d --remove-orphans
ExecStop=/usr/bin/docker compose -f docker-compose.prod.yml --env-file .env.production down
TimeoutStartSec=600

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable opsacademy.service

# 5b. Back up the database before any migration runs (set SKIP_BACKUP=1 to skip, e.g. the very first deploy)
if [ "${SKIP_BACKUP:-0}" != "1" ]; then
  # Read the URL from the env file without sourcing it (passwords may contain shell characters).
  env_value() { grep -E "^$1=" "${ENV_FILE}" | head -1 | cut -d= -f2-; }
  DB_URL="$(env_value MIGRATION_DATABASE_URL)"; [ -n "${DB_URL}" ] || DB_URL="$(env_value DATABASE_URL)"
  if [ -n "${DB_URL}" ]; then
    echo -e "${YELLOW}[backup] Dumping the database before migrating...${NC}"
    BACKUP_DATABASE_URL="${DB_URL}" "${ROOT_DIR}/scripts/backup-db.sh" "${ROOT_DIR}/backups" \
      || { echo -e "${RED}[ERROR] Backup failed; aborting before any migration. Set SKIP_BACKUP=1 to override.${NC}"; exit 1; }
  else
    echo -e "${YELLOW}[backup] No DATABASE_URL in ${ENV_FILE}; skipping backup.${NC}"
  fi
fi

# 6. Build and Launch Containers
echo -e "${YELLOW}[5/6] Building images and starting production containers...${NC}"
docker compose -f docker-compose.prod.yml --env-file .env.production build
docker compose -f docker-compose.prod.yml --env-file .env.production up -d --remove-orphans

# 7. Verification & Status Check
echo -e "${YELLOW}[6/6] Verifying service health...${NC}"
sleep 5

echo -e "\n${GREEN}Container Status:${NC}"
docker compose -f docker-compose.prod.yml ps

echo -e "\n${BLUE}==============================================================================${NC}"
echo -e "${GREEN}✓ OpsAcademy Production Stack successfully deployed!${NC}"
echo -e "  - Reverse Proxy (TLS / WebSockets): ports 80, 443"
echo -e "  - Data store: Supabase Postgres (DATABASE_URL); migrations run before the app starts"
echo -e "  - Isolated AI Hub: running on internal bridge network"
echo -e "  - Service auto-starts on EC2 reboot via systemd: opsacademy.service"
echo -e "${BLUE}==============================================================================${NC}"
